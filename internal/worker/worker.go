// Package worker runs the background jobs: anomaly checks, heatmap broadcasts, seeding and the demo simulator.
package worker

import (
	"context"
	"crypto/sha256"
	_ "embed"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"log"
	"time"

	"smartcity/internal/bl"
	"smartcity/internal/dl"
	"smartcity/internal/domain"
)

// RunScheduler runs the anomaly check and the heatmap broadcast on their intervals until ctx is cancelled.
func RunScheduler(ctx context.Context, anomaly *bl.AnomalyService, heat *bl.HeatmapService, checkEvery, heatEvery time.Duration) {
	check := time.NewTicker(checkEvery)
	hm := time.NewTicker(heatEvery)
	defer check.Stop()
	defer hm.Stop()
	for {
		select {
		case <-ctx.Done():
			return
		case <-check.C:
			if err := anomaly.Tick(ctx); err != nil && ctx.Err() == nil {
				log.Printf("anomaly tick: %v", err)
			}
		case <-hm.C:
			if err := heat.Broadcast(ctx); err != nil && ctx.Err() == nil {
				log.Printf("heatmap broadcast: %v", err)
			}
		}
	}
}

//go:embed seeddata/baku.json
var bakuJSON []byte

// seedData is the network generated by cmd/seedgen from OpenStreetMap: real bus stops and road geometry.
type seedData struct {
	Source   string `json:"source"`
	Stations []struct {
		Name string  `json:"name"`
		Lat  float64 `json:"lat"`
		Lng  float64 `json:"lng"`
	} `json:"stations"`
	Routes []struct {
		Code  string       `json:"code"`
		Name  string       `json:"name"`
		Buses int          `json:"buses"`
		Stops []int        `json:"stops"`
		Path  [][2]float64 `json:"path"`
	} `json:"routes"`
}

// SeedVersion identifies the embedded network; when it changes, existing databases are re-seeded.
func SeedVersion() string {
	sum := sha256.Sum256(bakuJSON)
	return hex.EncodeToString(sum[:6])
}

// Seed loads the real Baku network (OSM bus lines, stops and road paths) and its buses.
// It runs when the database has no network yet, or when the embedded seed data has changed since the
// last seed: then the demo network (stations, routes, buses and their live data) is replaced.
func Seed(ctx context.Context, store *dl.Store, fleet *bl.FleetService) error {
	version := SeedVersion()
	loaded, err := store.Meta.Get(ctx, "seed_version")
	if err != nil {
		return err
	}
	existing, err := store.Stations.List(ctx)
	if err != nil {
		return err
	}
	if loaded == version && len(existing) > 0 {
		return nil
	}
	if len(existing) > 0 {
		log.Printf("seed data changed (%q -> %q): replacing the demo network", loaded, version)
		if err := store.Meta.ResetNetwork(ctx); err != nil {
			return err
		}
	}
	var data seedData
	if err := json.Unmarshal(bakuJSON, &data); err != nil {
		return fmt.Errorf("seed data: %w", err)
	}
	ids := make([]int64, len(data.Stations))
	for i, s := range data.Stations {
		st := &domain.Station{Name: s.Name, Lat: s.Lat, Lng: s.Lng}
		if err := fleet.CreateStation(ctx, st); err != nil {
			return err
		}
		ids[i] = st.ID
	}
	for _, r := range data.Routes {
		stationIDs := make([]int64, len(r.Stops))
		for i, idx := range r.Stops {
			stationIDs[i] = ids[idx]
		}
		rt := &domain.Route{Code: r.Code, Name: r.Name, Path: r.Path}
		if err := fleet.CreateRoute(ctx, rt, stationIDs); err != nil {
			return err
		}
		for i := 0; i < r.Buses; i++ {
			rid := rt.ID
			b := &domain.Bus{Name: r.Code + "-" + string(rune('A'+i)), RouteID: &rid, Capacity: 80}
			if err := fleet.CreateBus(ctx, b); err != nil {
				return err
			}
		}
	}
	log.Printf("seeded %d real bus stops and %d bus lines (%s)", len(data.Stations), len(data.Routes), data.Source)
	return store.Meta.Set(ctx, "seed_version", version)
}
